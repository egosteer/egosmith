"""Release tiers and license bundle for a converted LeRobot dataset.

One LeRobot dataset = one source dataset = one licence. The *tier* decides what may leave the
building and shapes the conversion:

    open         full dataset (video + labels), redistributable under ``derived_license``
    gated        same content as ``open``, but published behind an access gate (e.g. HF gated repo)
    labels_only  no pixels: video stream dropped, plus a rehydration index (meta/source_frames.parquet)
    internal     never distributed; converted for in-house training only, README carries a banner

:func:`write_release_bundle` writes ``LICENSES/<source>/``, ``meta/release.json`` and a root
``README.md`` that states provenance, licence obligations and the modifications we made.
:func:`check_release_consistency` catches configuration that would violate the source licence
(labels-only job that still exports video, ShareAlike source released under a different licence, ...).
"""

from __future__ import annotations

import json
import shutil
from dataclasses import asdict, dataclass, field
from pathlib import Path

RELEASE_TIERS = ("open", "gated", "labels_only", "internal")
RELEASE_JSON = "meta/release.json"
LICENSES_DIR = "LICENSES"

